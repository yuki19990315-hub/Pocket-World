def rgb(red, green, blue):
    # framebuf stores little-endian words, while SPI requires high byte first.
    value = ((red & 248) << 8) | ((green & 252) << 3) | (blue >> 3)
    return ((value & 255) << 8) | (value >> 8)


class RoundLCD:
    def __init__(self):
        self.buffer = bytearray(SIZE * SIZE * 2)
        self.canvas = framebuf.FrameBuffer(self.buffer, SIZE, SIZE, framebuf.RGB565)
        self.spi = SPI(1, baudrate=40_000_000, polarity=0, phase=0,
                       sck=Pin(10), mosi=Pin(11), miso=None)
        self.cs = Pin(9, Pin.OUT, value=1)
        self.dc = Pin(8, Pin.OUT)
        self.backlight = Pin(2, Pin.OUT, value=0)
        reset = Pin(14, Pin.OUT, value=0)
        sleep_ms(50)
        reset.on()
        sleep_ms(120)
        for cmd, data in INIT:
            self.command(cmd, bytes(data))
        sleep_ms(120)
        self.command(0x29)
        sleep_ms(20)

    def command(self, cmd, data=b""):
        self.cs.off()
        try:
            self.dc.off()
            self.spi.write(bytes((cmd,)))
            if data:
                self.dc.on()
                self.spi.write(data)
        finally:
            self.cs.on()

    def show(self):
        self.command(0x2A, b"\x00\x00\x00\xef")
        self.command(0x2B, b"\x00\x00\x00\xef")
        self.command(0x2C, self.buffer)
